"""W5: the engine boundary is an artifact in the repo, not a memory.

``Docs/engine-live-files.txt`` and ``Docs/engine-unreachable-files.txt`` are
generated by ``tools/engine_reachability.py``. This file makes them a fact:

* the artifacts must match what the generator computes *now*
* a file may not sit in neither list
* a file that cannot be parsed fails the run, because "unparsed" is "unknown
  imports", never "no imports"

That last point is not theoretical. ``src/agent/src/skills/bundled_skills.py``
starts with a UTF-8 BOM; read as plain UTF-8 it is a ``SyntaxError``, and the
swallowed error made a live file and its importer look like dead code. The
regression test for it is here too.

The walk is an AST pass over ~140 files. It happens exactly once per session,
in ``state``; every test below only compares what that walk produced.
"""

from __future__ import annotations

import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Set

import pytest

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools import engine_reachability as reach  # noqa: E402


@pytest.fixture(scope="module")
def state() -> SimpleNamespace:
    """One walk, shared by every test in this file."""
    files = reach.engine_files()
    index = reach.build_index(files)
    live, dead = reach.reachable()

    recorded_live = set(reach._read_artifact(reach.LIVE_ARTIFACT))
    recorded_dead = set(reach._read_artifact(reach.DEAD_ARTIFACT))
    current_live = set(reach._rel(live))
    current_dead = set(reach._rel(dead))

    return SimpleNamespace(
        files=files,
        index=index,
        live=live,
        dead=dead,
        recorded_live=recorded_live,
        recorded_dead=recorded_dead,
        live_added=sorted(current_live - recorded_live),
        live_gone=sorted(recorded_live - current_live),
        dead_added=sorted(current_dead - recorded_dead),
        dead_gone=sorted(recorded_dead - current_dead),
    )


def test_every_engine_file_is_classified(state: SimpleNamespace) -> None:
    """A file in neither list would silently escape the boundary."""
    everything: Set[Path] = set(state.files)
    classified = state.live | state.dead
    assert classified == everything, (
        f"unclassified: {sorted(p.as_posix() for p in everything - classified)}"
    )
    assert not (state.live & state.dead), (
        f"in both lists: {sorted(p.as_posix() for p in state.live & state.dead)}"
    )


def test_every_file_parsed(state: SimpleNamespace) -> None:
    """A parse failure makes the answer unknown, so it fails the run."""
    assert reach.PARSE_FAILURES == [], (
        "files with unknown imports: "
        + ", ".join(f"{p.as_posix()} ({r})" for p, r in reach.PARSE_FAILURES)
    )


def test_live_artifact_matches_reality(state: SimpleNamespace) -> None:
    """The committed live list must equal what the generator produces."""
    assert state.live_added == [], (
        f"live but not recorded, re-run --write: {state.live_added}"
    )
    assert state.live_gone == [], (
        f"recorded live but now unreachable: {state.live_gone}"
    )


def test_unreachable_artifact_matches_reality(state: SimpleNamespace) -> None:
    """Drift in the other direction is drift too."""
    assert state.dead_added == [], (
        f"newly unreachable, not recorded: {state.dead_added}"
    )
    assert state.dead_gone == [], (
        f"recorded unreachable but reachable again: {state.dead_gone}"
    )


def test_artifacts_are_current_and_non_empty(state: SimpleNamespace) -> None:
    """Both files exist and the live list actually lists files."""
    assert reach.LIVE_ARTIFACT.exists(), "Docs/engine-live-files.txt is missing"
    assert reach.DEAD_ARTIFACT.exists(), (
        "Docs/engine-unreachable-files.txt is missing"
    )
    assert state.recorded_live, "the live artifact is empty"
    assert len(state.recorded_live) == len(state.live)
    assert len(state.recorded_dead) == len(state.dead)


def test_a_bom_prefixed_file_still_yields_its_imports(state: SimpleNamespace) -> None:
    """Regression: a UTF-8 BOM must not turn a file's imports into nothing.

    ``bundled_skills.py`` carries a BOM. Parsed as plain UTF-8 it raised
    ``SyntaxError``, the handler returned an empty set, and the whole subtree it
    imports was reported unreachable. Reading with ``utf-8-sig`` fixes it; this
    asserts the file the bug was found on still resolves its relative imports.
    """
    bundled = state.index.get("skills.bundled_skills")
    assert bundled is not None, "skills/bundled_skills.py disappeared from the index"

    imports = reach._imports_of(bundled, state.index)
    assert imports, "a file with 19 imports produced none, the BOM read regressed"
    assert state.index.get("agent_types.command") in imports, (
        "the `from ..agent_types.command import Command` edge is missing"
    )


def test_a_relative_import_resolves_from_the_package(state: SimpleNamespace) -> None:
    """``from .model_allowlist import ...`` must resolve to the sibling file."""
    options = state.index.get("utils.model.model_options")
    assert options is not None
    imports = reach._imports_of(options, state.index)
    assert state.index.get("utils.model.model_allowlist") in imports


def test_a_pip_package_is_not_engine_code(state: SimpleNamespace) -> None:
    """A name that is not in the tree resolves to nothing.

    ``sentence_transformers`` once matched an engine prefix and became a fake
    entry point, which inflated the live list with unrelated code.
    """
    assert reach._resolve("sentence_transformers", state.index) == []
    assert reach._resolve("src.ui.chat_panel", state.index) == [], (
        "Cortex's own src.ui must not resolve into the engine tree"
    )


def test_package_wins_over_module_of_the_same_name(state: SimpleNamespace) -> None:
    """Python's own rule, which is what stopped the count oscillating.

    ``utils/hooks.py`` and ``utils/hooks/__init__.py`` claim one dotted name.
    Set iteration order varies per process, so without a stated rule the dead
    count changed between runs (335 one run, 336 the next).
    """
    for name, path in state.index.items():
        if name == "utils.hooks" and path.name != "__init__.py":
            pytest.fail(f"{name} resolved to {path.name}, package must win")
